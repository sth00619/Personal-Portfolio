"""Behavioral checks for auction support, budgets, and outputs."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from src.experiment import (
    Auction, bid_value, conditional_win_curve, encode_features, replay, supported_bid,
)


def test_logged_bid_bounds_counterfactual_win() -> None:
    """Never permit a counterfactual bid above the observed logging bid."""
    auction = Auction("20130609000000000", price=80, logged_bid=50, clicks=1, pctr=0.01)
    assert supported_bid(auction, 500) == 50
    score = replay("constant", [auction], 1.0, 500, 0.01, 50)
    assert score.wins == 0
    assert score.clicks == 0


def test_replay_pays_observed_price_and_enforces_budget() -> None:
    """Second-price payments and the hard budget govern sequential wins."""
    auctions = [
        Auction(f"2013060900000{i:04d}", 100, 150, 1, 0.01)
        for i in range(4)
    ]
    score = replay("constant", auctions, 0.25, 150, 0.01, 50)
    assert score.wins == 2
    assert score.clicks == 2
    assert score.spend == pytest.approx(0.2)
    assert score.ecpc == pytest.approx(0.1)


def test_pacing_uses_event_time_and_stays_within_budget() -> None:
    """A paced policy remains budget safe with chronological events."""
    auctions = [Auction(f"20130609{hour:02d}0000000", 20, 100, 1, 0.01)
                for hour in range(24)]
    score = replay("paced_ortb", auctions, 0.1, 100, 0.01, 20)
    assert score.spend <= score.budget
    assert len(score.hourly_spend) == 24


def test_feature_vocabulary_comes_from_train_only() -> None:
    """Unknown evaluation categories map to the missing category code."""
    from src.experiment import FEATURE_COLUMNS

    train = pd.DataFrame({name: ["seen"] for name in FEATURE_COLUMNS})
    later = pd.DataFrame({name: ["future"] for name in FEATURE_COLUMNS})
    encoded_train, encoded_later = encode_features(train, later)
    assert (encoded_train.iloc[0] == 0).all()
    assert (encoded_later.iloc[0] == -1).all()


def test_conditional_win_curve_is_monotone() -> None:
    """Empirical eligibility rises as bids rise and fit stays positive."""
    bids, empirical, c = conditional_win_curve(np.array([1, 3, 8, 20]))
    assert np.all(np.diff(bids) > 0)
    assert np.all(np.diff(empirical) >= 0)
    assert c > 0
    assert bid_value("ortb", 0.01, 20, 0.01, c) > 0


def test_ship_gate_artifacts_when_present() -> None:
    """Persisted comparisons must match the machine-readable replay report."""
    project = Path(__file__).resolve().parents[1]
    report_path = project / "results" / "report.json"
    if not report_path.exists():
        pytest.skip("Experiment outputs are generated by docker compose run experiment")
    report = json.loads(report_path.read_text(encoding="utf-8"))
    table = pd.read_csv(project / "results" / "strategy_comparison.csv")
    assert set(table.strategy) == {"constant", "linear", "ortb", "paced_ortb"}
    assert len(report["scores"]) == 4
    for score in report["scores"]:
        row = table.loc[table.strategy == score["strategy"]].iloc[0]
        assert row.clicks == score["clicks"]
        assert row.spend == pytest.approx(score["spend"])
        assert row.spend <= row.budget
    assert (project / "results" / "hourly_spend.png").exists()
    assert (project / "results" / "win_curve.png").exists()
